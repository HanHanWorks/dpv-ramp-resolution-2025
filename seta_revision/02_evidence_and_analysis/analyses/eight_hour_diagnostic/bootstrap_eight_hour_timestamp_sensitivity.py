#!/usr/bin/env python3
"""Paired station-cluster bootstrap for the full +/-8 h clock diagnostic.

Consumes the station-month metrics generated by rerun_timestamp_alignment_sensitivity.py.
This is a negative-control sensitivity to an alternative UTC/Beijing interpretation,
not evidence that either alternative is the correct source-clock convention.
"""
import hashlib
import json
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
INPUT = HERE / "timestamp_redetection_sensitivity.csv"
OUTPUT = HERE / "timestamp_eight_hour_station_bootstrap.csv"
SHIFTS = [-8, 0, 8]
PRODUCTS = [
    "Tianji_2.5km", "Tianji_5km", "Tianji_10km", "Tianji_25km",
    "Tianji_27.5km", "ERA5_native_27.5km", "ERA5_regridded_2.5km",
]
N_BOOT = 50_000
SEED = 261112


def sha256(path):
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main():
    data = pd.read_csv(INPUT)
    data = data[
        data["solar_qc_group"].eq("primary_solar_qc")
        & data["mask_scope"].eq("all_products_common_hours")
        & data["tolerance_h"].eq(1)
        & data["station_time_shift_h"].isin(SHIFTS)
    ].copy()
    stations = sorted(data["station_id"].unique())
    months = sorted(data["month"].unique())
    tensor = np.empty((len(stations), len(months), len(PRODUCTS), len(SHIFTS)))
    for pi, product in enumerate(PRODUCTS):
        for si, shift in enumerate(SHIFTS):
            cell = data[
                data["product"].eq(product)
                & data["station_time_shift_h"].eq(shift)
            ].pivot(index="station_id", columns="month", values="csi")
            cell = cell.reindex(index=stations, columns=months)
            if cell.isna().any().any():
                raise ValueError("Incomplete paired station-month grid: {} / {}".format(product, shift))
            tensor[:, :, pi, si] = cell.to_numpy()

    rng = np.random.default_rng(SEED)
    boot = np.empty((N_BOOT, len(PRODUCTS), len(SHIFTS)))
    for start in range(0, N_BOOT, 500):
        n = min(500, N_BOOT - start)
        draw = rng.integers(0, len(stations), size=(n, len(stations)))
        # Resample station IDs as clusters and retain both months for each draw.
        boot[start:start+n] = tensor[draw].mean(axis=(1, 2))
    point = tensor.mean(axis=(0, 1))

    rows = []
    for pi, product in enumerate(PRODUCTS):
        for si, shift in enumerate(SHIFTS):
            values = boot[:, pi, si]
            rows.append({
                "estimand": "macro_station_month_CSI",
                "product_or_contrast": product,
                "station_time_shift_h": shift,
                "point_estimate": point[pi, si],
                "ci95_low": np.quantile(values, .025),
                "ci95_high": np.quantile(values, .975),
                "n_station_clusters": len(stations),
                "station_months_per_cluster": len(months),
                "bootstrap_replicates": N_BOOT,
            })
    fine = PRODUCTS.index("Tianji_2.5km")
    coarse = PRODUCTS.index("Tianji_27.5km")
    for si, shift in enumerate(SHIFTS):
        values = boot[:, coarse, si] - boot[:, fine, si]
        rows.append({
            "estimand": "paired_CSI_contrast",
            "product_or_contrast": "Tianji_27.5km_minus_Tianji_2.5km",
            "station_time_shift_h": shift,
            "point_estimate": point[coarse, si] - point[fine, si],
            "ci95_low": np.quantile(values, .025),
            "ci95_high": np.quantile(values, .975),
            "n_station_clusters": len(stations),
            "station_months_per_cluster": len(months),
            "bootstrap_replicates": N_BOOT,
        })
    for pi, product in enumerate(PRODUCTS):
        for si in [0, 2]:
            values = boot[:, pi, si] - boot[:, pi, 1]
            rows.append({
                "estimand": "paired_shift_minus_zero_CSI_change",
                "product_or_contrast": product,
                "station_time_shift_h": SHIFTS[si],
                "point_estimate": point[pi, si] - point[pi, 1],
                "ci95_low": np.quantile(values, .025),
                "ci95_high": np.quantile(values, .975),
                "n_station_clusters": len(stations),
                "station_months_per_cluster": len(months),
                "bootstrap_replicates": N_BOOT,
            })
    result = pd.DataFrame(rows)
    result.to_csv(OUTPUT, index=False)
    analysis_meta = json.loads((HERE / "timestamp_redetection_sensitivity_metadata.json").read_text(encoding="utf-8"))
    metadata = {
        "input_metrics": INPUT.name,
        "input_sha256": sha256(INPUT),
        "station_input": analysis_meta["station_input"],
        "station_input_sha256": analysis_meta["station_input_sha256"],
        "model_inputs_sha256": analysis_meta["model_inputs_sha256"],
        "scope": "primary solar-QC group, 2025-04 and 2025-07, all-products common-hour mask, 200 W m-2 h-1 threshold, 1 h event tolerance",
        "station_time_shift_definition": "positive shifts station observation timestamps later relative to model local timestamps; +/-8 h are diagnostic alternatives for the source clock interpretation",
        "bootstrap": "paired station-cluster percentile bootstrap; resample station IDs with replacement and retain both monthly rows per sampled station",
        "replicates": N_BOOT,
        "seed": SEED,
        "limitations": [
            "Only seven primary-QC station clusters are available; intervals are exploratory and do not address spatial dependence.",
            "The +/-8 h diagnostics do not identify the correct provider clock convention.",
            "Station observations are author-identified as Hubei data; provider and instrument provenance were not independently verified in this analysis."
        ],
        "output": OUTPUT.name,
        "output_sha256": sha256(OUTPUT),
    }
    OUTPUT.with_name("timestamp_eight_hour_station_bootstrap_metadata.json").write_text(
        json.dumps(metadata, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(result[result["estimand"].eq("paired_CSI_contrast")].to_string(index=False))


if __name__ == "__main__":
    main()
